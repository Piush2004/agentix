"use client";
import React, { useEffect, useState } from 'react';
import { motion } from 'framer-motion';
import { 
  Download,
  Share2,
  MoreHorizontal,
  TrendingUp,
  Users,
  Target,
  BarChart2,
  Loader2,
  AlertCircle
} from 'lucide-react';
import { usePlatformStore } from '@/store/platformStore';
import {
  BarChart,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  Legend,
  ResponsiveContainer
} from 'recharts';
export default function ReportsPage() {
  const { 
    datasetName,
    isLoading,
    error,
    automlData,
    insightsData,
    recommendationsData,
    fetchReports,
    fetchInsights,
    fetchRecommendations,
    fetchAutoML
  } = usePlatformStore();

  const [loadingInitial, setLoadingInitial] = useState(true);

  useEffect(() => {
    async function loadData() {
      if (datasetName) {
        setLoadingInitial(true);
        await Promise.all([
          fetchReports(),
          fetchInsights(),
          fetchRecommendations(),
          fetchAutoML()
        ]);
        setLoadingInitial(false);
      }
    }
    loadData();
  }, [datasetName, fetchReports, fetchInsights, fetchRecommendations, fetchAutoML]);

  if (!datasetName) {
    return (
      <div className="w-full flex flex-col items-center justify-center pt-20 px-4">
        <AlertCircle size={48} className="text-text-tertiary mb-4" />
        <h2 className="text-xl font-bold text-text-primary mb-2 font-heading">No Active Dataset</h2>
        <p className="text-text-secondary">Please upload or select a dataset to view intelligence reports.</p>
      </div>
    );
  }

  if (loadingInitial) {
    return (
      <div className="w-full flex flex-col items-center justify-center pt-20 px-4 h-[60vh]">
        <Loader2 size={48} className="text-primary animate-spin mb-4" />
        <h2 className="text-xl font-bold text-text-primary mb-2 font-heading">Generating Reports</h2>
        <p className="text-text-secondary">Analyzing models and compiling insights...</p>
      </div>
    );
  }

  if (error) {
    return (
      <div className="w-full flex flex-col items-center justify-center pt-20 px-4 h-[60vh]">
        <AlertCircle size={48} className="text-danger mb-4" />
        <h2 className="text-xl font-bold text-text-primary mb-2 font-heading">Error Loading Reports</h2>
        <p className="text-text-secondary">{error}</p>
      </div>
    );
  }

  const models = automlData?.leaderboard?.slice(0, 3) || [];
  const insights = insightsData?.insights || [];
  const recommendations = recommendationsData?.actions || [];

  return (
    <div className="w-full flex flex-col gap-8 pb-16 max-w-5xl mx-auto pt-6 px-4 md:px-0">
      
      {/* Header Actions */}
      <div className="flex flex-col md:flex-row justify-between items-start md:items-center gap-4">
        <div>
          <h1 className="text-3xl font-bold tracking-tight text-text-primary mb-2 font-heading">Executive Report: Model Insights</h1>
          <p className="text-text-secondary text-[15px]">Generated by Agentix Analyst</p>
        </div>
        <div className="flex items-center gap-3">
          <button className="px-4 py-2 bg-white border border-border text-text-secondary rounded-lg font-medium text-[13px] hover:bg-surface-hover hover:text-text-primary transition-all flex items-center gap-2 shadow-sm">
            <Share2 size={16} /> Share
          </button>
          <button className="px-4 py-2 bg-primary text-white rounded-lg font-medium text-[13px] hover:bg-primary-hover transition-all flex items-center gap-2 shadow-sm">
            <Download size={16} /> Export PDF
          </button>
          <button className="p-2 bg-white border border-border text-text-secondary rounded-lg hover:bg-surface-hover transition-all shadow-sm">
            <MoreHorizontal size={18} />
          </button>
        </div>
      </div>

      <motion.div 
        initial={{ opacity: 0, y: 10 }}
        animate={{ opacity: 1, y: 0 }}
        className="bg-white border border-border rounded-2xl shadow-sm overflow-hidden"
      >
        <div className="p-8 md:p-12">
          
          {/* Executive Summary */}
          <div className="mb-12">
            <h2 className="text-xl font-bold text-text-primary mb-4 font-heading border-b border-border pb-3">Executive Summary</h2>
            {insights.length > 0 ? (
              <ul className="space-y-3 list-disc list-outside ml-5 text-text-secondary text-[15px] leading-relaxed">
                {insights.map((insight, idx) => (
                  <li key={idx}>{insight}</li>
                ))}
              </ul>
            ) : (
              <p className="text-text-secondary text-[15px] leading-relaxed">
                No insights available at this time.
              </p>
            )}
          </div>

          {/* KPIs */}
          <div className="mb-12">
            <h2 className="text-xl font-bold text-text-primary mb-4 font-heading border-b border-border pb-3">Model Performance Indicators</h2>
            <div className="grid grid-cols-1 md:grid-cols-3 gap-6 mt-6">
              
              {models.map((model, idx) => {
                const icons = [TrendingUp, Users, Target];
                const Icon = icons[idx % icons.length];
                const colors = [
                  { bg: 'bg-success/10', text: 'text-success' },
                  { bg: 'bg-primary/10', text: 'text-primary' },
                  { bg: 'bg-warning/10', text: 'text-warning' }
                ];
                const color = colors[idx % colors.length];

                return (
                  <div key={idx} className="bg-surface p-5 rounded-xl border border-border">
                    <div className="flex items-center gap-3 mb-3">
                      <div className={`p-2 ${color.bg} ${color.text} rounded-lg`}>
                        <Icon size={18} />
                      </div>
                      <span className="font-bold text-text-secondary text-sm uppercase tracking-wider line-clamp-1" title={model.model}>{model.model}</span>
                    </div>
                    <div className="flex items-end gap-3">
                      <p className="text-3xl font-bold text-text-primary">
                        {(model.r2_score !== undefined ? model.r2_score.toFixed(3) : model.cv_mean?.toFixed(3) || 'N/A')}
                      </p>
                      <span className={`text-sm font-bold ${color.text} mb-1`}>Score</span>
                    </div>
                  </div>
                );
              })}
              
              {models.length === 0 && (
                <div className="col-span-1 md:col-span-3 text-center text-text-secondary py-8 bg-surface rounded-xl border border-border">
                  No model metrics available yet.
                </div>
              )}

            </div>
          </div>

          {/* Charts Area */}
          <div className="mb-12">
            <h2 className="text-xl font-bold text-text-primary mb-4 font-heading border-b border-border pb-3">Performance Distribution</h2>
            {models.length > 0 ? (
              <div className="w-full h-80 bg-surface rounded-xl border border-border mt-6 p-4 pt-8">
                <ResponsiveContainer width="100%" height="100%">
                  <BarChart
                    data={models}
                    margin={{ top: 0, right: 20, left: -20, bottom: 0 }}
                  >
                    <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="#E5E7EB" />
                    <XAxis 
                      dataKey="model" 
                      axisLine={false} 
                      tickLine={false} 
                      tick={{fill: '#6B7280', fontSize: 12, fontWeight: 500}} 
                      dy={10}
                    />
                    <YAxis 
                      axisLine={false} 
                      tickLine={false} 
                      tick={{fill: '#6B7280', fontSize: 12}} 
                      domain={[0, 'dataMax + 0.1']} 
                    />
                    <Tooltip 
                      contentStyle={{ borderRadius: '12px', border: '1px solid #E5E7EB', boxShadow: '0 10px 15px -3px rgb(0 0 0 / 0.1)', padding: '12px' }}
                      cursor={{fill: '#F3F4F6'}}
                    />
                    <Legend iconType="circle" wrapperStyle={{ fontSize: '12px', paddingTop: '20px' }}/>
                    <Bar dataKey="r2_score" name="R2 Score" fill="#0EA5E9" radius={[6, 6, 0, 0]} maxBarSize={60} />
                    <Bar dataKey="cv_mean" name="Cross-Validation Mean" fill="#8B5CF6" radius={[6, 6, 0, 0]} maxBarSize={60} />
                  </BarChart>
                </ResponsiveContainer>
              </div>
            ) : (
              <div className="w-full h-64 bg-surface rounded-xl border border-border border-dashed flex flex-col items-center justify-center text-text-tertiary gap-3 mt-6">
                <BarChart2 size={32} />
                <p className="text-sm font-medium">No chart data available.</p>
              </div>
            )}
          </div>

          {/* Recommendations */}
          <div>
            <h2 className="text-xl font-bold text-text-primary mb-4 font-heading border-b border-border pb-3">AI Recommendations</h2>
            {recommendations.length > 0 ? (
              <ul className="space-y-4 mt-6">
                {recommendations.map((rec, idx) => (
                  <li key={idx} className="flex gap-4">
                    <span className="w-6 h-6 rounded-full bg-primary-light text-primary flex items-center justify-center font-bold text-xs shrink-0 mt-0.5">
                      {idx + 1}
                    </span>
                    <div>
                      <p className="text-[14px] text-text-secondary leading-relaxed">{rec}</p>
                    </div>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="mt-6 text-text-secondary text-[15px]">No recommendations available.</p>
            )}
          </div>

        </div>
      </motion.div>
    </div>
  );
}
